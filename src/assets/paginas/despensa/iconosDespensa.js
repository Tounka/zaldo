// Alias para compatibilidad con código existente
export const ICONOS_PAPER_MARIO = ICONOS_DESPENSA;

const RUTAS_VALIDAS_DESPENSA = new Set(ICONOS_DESPENSA.map((i) => i.ruta));

/**
 * Detecta automáticamente el ícono más idóneo a partir del nombre del producto
 * o su categoría, seleccionando stickers ilustrados de despensa.
 */
export const detectarIconoProducto = (nombre = "", categoria = "Despensa") => {
    const texto = String(nombre || "")
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "");

    // 1. Coincidencias específicas por nombre en el catálogo oficial
    for (const item of ICONOS_DESPENSA) {
        if (
            item.keywords.some((kw) => {
                const kwNorm = kw
                    .toLowerCase()
                    .normalize("NFD")
                    .replace(/[\u0300-\u036f]/g, "");
                return texto.includes(kwNorm);
            })
        ) {
            return item.ruta;
        }
    }

    // 2. Fallbacks según categoría
    if (categoria === "Refrigerados" || categoria === "Lácteos") return "/despensa/iconos/leche.jpg";
    if (categoria === "Limpieza") return "/despensa/iconos/detergente.jpg";
    if (categoria === "Baño") return "/despensa/iconos/papel_higienico.jpg";
    if (categoria === "Higiene") return "/despensa/iconos/pasta_dental.jpg";
    if (categoria === "Bebidas") return "/despensa/iconos/refresco.jpg";
    if (categoria === "Botanas" || categoria === "Dulces") return "/despensa/iconos/galletas.jpg";
    if (categoria === "Frutas" || categoria === "Verduras" || categoria === "Frescos") return "/despensa/iconos/manzana.jpg";
    if (categoria === "Hogar") return "/despensa/iconos/detergente.jpg";

    return "/despensa/iconos/atun.jpg";
};

/**
 * Resuelve la imagen correcta para cualquier producto.
 * Valida que el archivo exista en el catálogo de stickers oficiales de Despensa.
 * Si tiene una ruta SVG, antigua o rota, la sustituye automáticamente.
 */
export const resolverImagenProducto = (prod = {}) => {
    const imagen = prod?.imagen || prod?.presentacionImagen;

    // Si coincide con un sticker de despensa oficial
    if (typeof imagen === "string" && RUTAS_VALIDAS_DESPENSA.has(imagen)) {
        return imagen;
    }

    // Si es una URL externa completa
    if (
        typeof imagen === "string" &&
        (imagen.startsWith("http://") || imagen.startsWith("https://") || imagen.startsWith("data:"))
    ) {
        return imagen;
    }

    // Para cualquier otro caso (SVG, imágenes viejas, rutas inválidas)
    return detectarIconoProducto(prod?.nombre, prod?.categoria);
};

